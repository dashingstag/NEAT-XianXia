#!/usr/bin/env python3
"""Build the LOD review board: assets/LOD_BOARD.html (self-contained,
animated) plus assets/parked/lod/LOD_BOARD.md for repo review.

Consumes assets/parked/lod/manifest.json emitted by gen_lod.py.
Rebuild: python3 assets/tools/gen_lod.py && python3 assets/tools/build_lod_board.py
"""
import base64
import html
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOD = os.path.join(ROOT, "parked", "lod")

CATS = [
    ("settlements", "Settlements",
     "Stage shapes match the live LOD1 markers in `field.gd`; at LOD2+ the "
     "market well and housing ring draw in full."),
    ("buildings", "Buildings & sites",
     "Glyph = parked `site-glyphs-xianxia` texture. LOD3 adds a per-site "
     "ambient accent (smoke, lantern glow, swinging sign, turning mill wheel)."),
    ("patches", "Resource patches",
     "LOD1 keeps the in-game convention: color dots scale with stock, mines "
     "are ore-colored diamonds."),
    ("terrain", "Flora & terrain features",
     "Tree canopies sway, water ripples, mist drifts. Features that the "
     "engine draws procedurally (roads, coast, hill, fog) get LOD2 cells "
     "under `parked/lod/anim/`."),
    ("people", "People",
     "LOD1 is the existing action-colored dot (MultiMesh quad); LOD2 shows "
     "the villager-atlas stance sheet; LOD3 is the 8-frame walk cycle. "
     "Work-cycle strips ship alongside as `anim/<id>-work.png`."),
    ("wildlife", "Wildlife",
     "LOD1 species dot (size/color per `field.gd`); LOD3 is the 4-frame "
     "walk cycle. Graze/flee/dead rows already exist in the animal atlas."),
    ("overlays", "Overlays & FX",
     "Interface marks: convoys, rally points, zones, selection, trade "
     "routes and the discovery reveal."),
]
CAT_ORDER = [c for c, _, _ in CATS]


def b64(path):
    with open(path, "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


def img(path, size=None, extra=""):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return f"<span class=miss>missing<br>{html.escape(path)}</span>"
    st = f"width:{size}px" if size else ""
    return f'<img src="{b64(p)}" style="{st}{extra}">'


def main():
    rows = json.load(open(os.path.join(LOD, "manifest.json")))
    by_cat = {c: [] for c in CAT_ORDER}
    scene = None
    for r in rows:
        if r["cat"] == "scene":
            scene = r
        elif r["cat"] in by_cat:
            by_cat[r["cat"]].append(r)

    h = ["<!doctype html><meta charset=utf-8>",
         "<title>NEAT Xianxia — LOD Asset Board</title>",
         "<style>",
         "body{font:14px/1.5 system-ui;background:#10151c;color:#e8e2d2;",
         "max-width:1240px;margin:24px auto;padding:0 16px}",
         "h1{font-size:22px;margin-bottom:4px}",
         "h2{margin-top:40px;border-bottom:1px solid #38bdf8;padding-bottom:4px}",
         "h3{color:#d4a94e;font-size:14px;margin:28px 0 6px}",
         "table{border-collapse:collapse;width:100%}",
         "td,th{border:1px solid #2a3442;padding:6px 10px;vertical-align:middle}",
         "th{text-align:left;color:#38bdf8}",
         "th.lod{width:150px}",
         "code{background:#1b2430;padding:1px 5px;border-radius:3px;color:#d4a94e}",
         "img{image-rendering:pixelated;background:#1b2430;border-radius:4px}",
         ".cell{background:#141a12;text-align:center;min-width:110px}",
         ".cell img{max-width:230px;max-height:96px;min-width:32px}",
         ".note{color:#9aa8b5}.dim{color:#6d7a85;font-size:12px}",
         ".miss{color:#e63946;font-size:11px}",
         ".tri{display:flex;gap:18px;flex-wrap:wrap}",
         ".tri figure{margin:0;text-align:center}",
         ".tri img{width:384px;image-rendering:pixelated;background:#1b2430;border:1px solid #2a3442}",
         ".tri figcaption{color:#d4a94e;font-size:13px;margin-top:4px}",
         ".band{display:inline-block;border:1px solid #2a3442;border-radius:6px;",
         "padding:8px 14px;margin:10px 8px 0 0;background:#141a12}",
         "</style>",
         "<h1>NEAT Xianxia — LOD Asset Board</h1>",
         "<p class=note>Pre-integration review: every drawable object at the "
         "three gameplay fidelities. Levels follow <code>field.gd</code>: "
         "<b>L1 OVERVIEW</b> (zoom &lt;2× — dots & landmark shapes), "
         "<b>L2 INDIVIDUAL FEATURES</b> (zoom &lt;5× — every building and "
         "individual drawn), <b>L3 ANIMATED INDIVIDUALS</b> (zoom ≥5× — "
         "animation for all assets). All cells are generated by "
         "<code>assets/tools/gen_lod.py</code>; rebuild with "
         "<code>python3 assets/tools/gen_lod.py &amp;&amp; "
         "python3 assets/tools/build_lod_board.py</code>. "
         "L3 previews are animated PNGs — they loop in place.</p>"]

    # ---------------- scene triptych ----------------
    if scene:
        h += ["<h2>The same street, three levels</h2>",
              "<div class=tri>",
              f"<figure>{img(scene['l1'])}<figcaption>L1 — dots & landmarks</figcaption></figure>",
              f"<figure>{img(scene['l2'])}<figcaption>L2 — all objects drawn</figcaption></figure>",
              f"<figure>{img(scene['l3'])}<figcaption>L3 — everything animated</figcaption></figure>",
              "</div>"]

    # ---------------- legend ----------------
    h += ["<h3>Reading the board</h3>",
          "<p class=note>L1 shows the 24px overview marker. The villager dot "
          "changes color with the current action (<code>field.gd</code> "
          "palette) — see the first row of People for the full legend. "
          "Dormant content (immortal figures, spirit beasts, future patch "
          "kinds) is included so the LOD contract is already proven for "
          "it.</p>"]

    # ---------------- category tables ----------------
    for cat, title, note in CATS:
        if not by_cat[cat]:
            continue
        h += [f"<h2>{title}</h2><p class=note>{note}</p>",
              "<table><tr><th>ID</th><th>Name</th>"
              "<th class=lod>L1 — Overview</th>"
              "<th class=lod>L2 — Drawn</th>"
              "<th class=lod>L3 — Animated</th><th>Notes</th></tr>"]
        for r in by_cat[cat]:
            l3 = img(r["l3"]) if r["l3"].endswith(".png") else ""
            fr = f"{r['frames']} fr" if r["frames"] else "static"
            h.append(
                f"<tr><td><code>{html.escape(r['id'])}</code></td>"
                f"<td>{html.escape(r['name'])}</td>"
                f"<td class=cell>{img(r['l1'])}</td>"
                f"<td class=cell>{img(r['l2'])}</td>"
                f"<td class=cell>{l3}<div class=dim>{fr}</div></td>"
                f"<td class=note>{html.escape(r['note'])}</td></tr>")
        h.append("</table>")

    # ---------------- footer ----------------
    h += ["<h2>Integration map</h2>",
          "<p class=note>LOD1 markers: <code>parked/lod/dots/*.png</code> "
          "(24px). LOD2 glyphs: existing families under "
          "<code>parked/{site-glyphs-xianxia,terrain-flora-xianxia,"
          "villager-atlas-v2,animal-table-xianxia}</code> plus new cells in "
          "<code>parked/lod/l2/</code>. LOD3: horizontal strips in "
          "<code>parked/lod/anim/</code> (8×64px, 10fps to match the shader "
          "clock); the villager/animal atlases already carry equivalent "
          "rows. Everything stays <b>parked</b> until approved; one atomic "
          "integration commit per family.</p>",
          "<p class=dim>Generated by assets/tools/build_lod_board.py — "
          "do not hand-edit.</p>"]

    open(os.path.join(ROOT, "LOD_BOARD.html"), "w",
         encoding="utf-8").write("\n".join(h))

    # ---------------- markdown twin ----------------
    md = ["# NEAT Xianxia — LOD Asset Board", "",
          "Pre-integration review of all drawable objects at the three "
          "gameplay fidelities (L1 overview dots/landmarks, L2 drawn "
          "individuals, L3 animation). Animated previews are APNG files; "
          "open `assets/LOD_BOARD.html` for the live board.", ""]
    for cat, title, note in CATS:
        if not by_cat[cat]:
            continue
        md += [f"## {title}", "", note, "",
               "| ID | L1 | L2 | L3 | Notes |", "|---|---|---|---|---|"]
        for r in by_cat[cat]:
            md.append(f"| `{r['id']}` | ![]({r['l1'].replace('parked/lod/', '')}) "
                      f"| ![]({r['l2'].replace('parked/', '../')}) "
                      f"| ![]({r['l3'].replace('parked/lod/', '')}) "
                      f"| {r['note']} |")
        md.append("")
    open(os.path.join(LOD, "LOD_BOARD.md"), "w",
         encoding="utf-8").write("\n".join(md))
    print(f"board written: {sum(len(v) for v in by_cat.values())} rows")


if __name__ == "__main__":
    main()
